"""The planner sees the owner's decisions on closed proposals."""

import json
import subprocess
import unittest
from unittest.mock import patch

import nexus_tick
from modules.nexus_planner import planning_prompt
from tests.test_nexus_initiative import InitiativeFixture

DECISION = {"title": "Gate judges itself", "reason": "Not planned: the gate must stay independent."}


class OwnerDecisionsTests(unittest.TestCase):
    def test_prompt_lists_decisions(self):
        prompt = planning_prompt([{"number": 1, "author": {"login": "tire0011"}, "title": "x", "body": ""}], decisions=[DECISION])
        self.assertIn("OWNER DECISIONS", prompt)
        self.assertIn("Gate judges itself: Not planned: the gate must stay independent.", prompt)

    def test_initiative_passes_decisions_and_survives_a_failing_lister(self):
        seen = []

        class Planner:
            def choose(self, issues, recent=None, exhausted=None, proposals=None, decisions=None):
                seen.append(decisions)
                return None

        def broken():
            raise RuntimeError("gh down")

        for lister, expected in ((lambda: [DECISION], [DECISION]), (broken, [])):
            fx = InitiativeFixture()
            svc = fx.service(
                issue_lister=lambda: [{"number": 1, "author": {"login": "tire0011"}, "title": "Work", "body": ""}],
                planner=Planner(), decision_lister=lister,
            )
            self.addCleanup(svc.close)
            svc.tick()
            self.assertEqual(seen[-1], expected)

    def test_reason_is_the_last_comment_without_footer(self):
        def fake_run(argv, **_kwargs):
            if "comments" in argv[2]:
                out = [
                    {"body": "first", "user": {"login": "tire0011"}},
                    {"body": "Not planned: covered by #478.\n\n---\n_Generated by Claude_",
                     "user": {"login": "tire0011"}},
                ]
            else:
                out = [{"number": 487, "author": {"login": "tire0011"}, "title": "Merge main at adoption", "state_reason": "not_planned"}]
            return subprocess.CompletedProcess(argv, 0, json.dumps(out), "")

        with patch("nexus_tick.subprocess.run", side_effect=fake_run):
            decisions = nexus_tick._owner_decisions("/repo")
        self.assertEqual(decisions, [{"title": "Merge main at adoption", "reason": "Not planned: covered by #478."}])


if __name__ == "__main__":
    unittest.main()
